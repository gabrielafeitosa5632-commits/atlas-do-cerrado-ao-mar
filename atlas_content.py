def get_section(number: int) -> dict | None:
    return next((section for section in SECTIONS if section["number"] == number), None)


def build_export_markdown() -> str:
    lines = [
        "# ATLAS DIGITAL / PROJETO TAMAR",
        "",
        "Do Cerrado ao mar: a experiência dos estudantes do IFB entre ciência, conservação e cultura oceânica.",
        "",
        "> Versão-base editável. Registros de visita devem ser confirmados pela equipe.",
        "",
    ]
    for section in SECTIONS:
        lines.extend(
            [
                f'## {section["number"]}. {section["title"]}',
                "",
                section["intro"],
                "",
            ]
        )
        for block in section.get("blocks", []):
            lines.extend([f'### {block["title"]}', ""])
            if block.get("body"):
                lines.extend([block["body"], ""])
            for item in block.get("bullets", []):
                lines.append(f"- {item}")
            if block.get("bullets"):
                lines.append("")
        if section.get("reflection"):
            lines.extend(["### Para registrar", "", section["reflection"], ""])
    lines.extend(["## Glossário", ""])
    for term, definition in GLOSSARY:
        lines.append(f"- **{term}:** {definition}")
    lines.extend(["", "## Referências", ""])
    for ref in REFERENCES.values():
        lines.append(f'- {ref["organization"]}. **{ref["title"]}.** {ref["url"]}')
    lines.append("")
    return "\n".join(lines)

